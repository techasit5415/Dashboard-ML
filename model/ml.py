import json
from pathlib import Path
import numpy as np
import pandas as pd

def progress(percent, message):
    print(f'[{percent:3d}%] {message}', flush=True)

def main():
    # กำหนด Path ให้ทำงานบน Colab โดยตรง
    src = Path('data')
    out = Path('output')
    out.mkdir(parents=True, exist_ok=True)

    progress(5, 'Reading source files')
    p = pd.read_json(src / 'profile.json', lines=True).rename(columns={'id': 'person'})
    o = pd.read_json(src / 'portfolio.json', lines=True).rename(columns={'id': 'offer_id'})
    t = pd.read_json(src / 'transcript.json', lines=True)

    summary = {'raw_rows': {'profile': len(p), 'portfolio': len(o), 'transcript': len(t)}}
    summary['missing_before'] = {c: int(p[c].isna().sum()) for c in ['age', 'income', 'gender']}
    summary['age_118'] = int(p.age.eq(118).sum())
    assert p.person.is_unique and o.offer_id.is_unique

    t['offer_id'] = t.value.map(lambda v: v.get('offer id', v.get('offer_id')))
    t['amount'] = t.value.map(lambda v: v.get('amount', 0.0))

    # ลบ Event ที่ซ้ำซ้อนกัน
    key = t[['person', 'event', 'time']].astype(str).agg('|'.join, axis=1) + t.value.map(lambda v: json.dumps(v, sort_keys=True))
    summary['duplicate_events_removed'] = int(key.duplicated().sum())
    t = t.loc[~key.duplicated()].copy()
    progress(20, 'Source files loaded; duplicate events removed')

    # จัดการข้อมูลลูกค้า (Profile)
    p.loc[p.age.eq(118), 'age'] = np.nan
    p['age_missing'] = p.age.isna().astype(int)
    p['income_missing'] = p.income.isna().astype(int)
    p['gender_missing'] = p.gender.isna().astype(int)
    p['gender'] = p.gender.fillna('Unknown')
    dates = pd.to_datetime(p.became_member_on.astype(str), format='%Y%m%d', errors='raise')
    p['member_year'], p['member_month'] = dates.dt.year, dates.dt.month

    # จัดการข้อมูลโปรโมชัน (Portfolio)
    o['duration_hours'] = o.duration * 24
    for ch in ['email', 'mobile', 'social', 'web']:
        o['channel_' + ch] = o.channels.map(lambda x: int(ch in x))

    # กรองเฉพาะ offer received ของ bogo และ discount
    r = t.loc[t.event.eq('offer received'), ['person', 'offer_id', 'time']].merge(o, on='offer_id', validate='many_to_one')
    summary['informational_excluded'] = int(r.offer_type.eq('informational').sum())
    r = r[r.offer_type.isin(['bogo', 'discount'])].copy()
    r['expires_at'] = r.time + r.duration_hours
    r['receipt_id'] = r.person + '_' + r.offer_id + '_' + r.time.astype(str)
    assert r.receipt_id.is_unique

    # ตัดโปรซ้ำซ้อนที่ช่วงเวลาทับซ้อนกันออก
    r = r.sort_values(['person', 'offer_id', 'time']).copy()
    gap = r.groupby(['person', 'offer_id']).time.diff()
    prev_overlap = gap.le(r.duration_hours)
    next_overlap = gap.groupby([r.person, r.offer_id]).shift(-1).le(r.duration_hours)
    ambiguous_mask = prev_overlap | next_overlap
    summary['overlapping_receipts_excluded'] = int(ambiguous_mask.sum())
    r = r.loc[~ambiguous_mask].copy()
    progress(40, 'Eligible offers selected')

    # ตัดโปรที่ยังไม่หมดอายุตอนจบช่วงสังเกตการณ์
    end = int(t.time.max())
    summary['observation_end_hour'] = end
    summary['incomplete_followup_excluded'] = int((r.expires_at > end).sum())
    r = r[r.expires_at <= end].copy()

    # =========================================================================
    # จุดที่แก้บั๊ก: จับคู่ Target 'completed' โดยรักษาแถวและ Index ไม่ให้หลุด
    # =========================================================================
    comp = t.loc[t.event.eq('offer completed'), ['person', 'offer_id', 'time']].dropna(subset=['offer_id']).rename(columns={'time': 'completion_time'})
    left = r.sort_values(['time', 'person', 'offer_id']).reset_index(drop=True)
    right = comp.sort_values(['completion_time', 'person', 'offer_id']).reset_index(drop=True)

    matched = pd.merge_asof(
        left,
        right,
        left_on='time',
        right_on='completion_time',
        by=['person', 'offer_id'],
        direction='forward',
        allow_exact_matches=True
    )
    # ผูก completed เข้ากับตาราง matched ตรงๆ แล้วส่งต่อให้ r ทันที
    matched['completed'] = matched.completion_time.le(matched.expires_at).fillna(False).astype('int8')
    r = matched.drop(columns=['completion_time']).copy()
    progress(55, 'Offer outcomes matched (Bug fixed: Index aligned 100%)')

    # สร้าง Feature ประวัติในอดีต (ก่อนเวลารับโปรโมชัน)
    tx = t[t.event.eq('transaction')].groupby(['person', 'time'], as_index=False).amount.sum().sort_values(['time', 'person'])
    tx['past_transaction_count'] = tx.groupby('person').cumcount() + 1
    tx['past_total_spend'] = tx.groupby('person').amount.cumsum()
    tx['past_average_spend'] = tx.past_total_spend / tx.past_transaction_count

    hist_sources = []
    for ev, col in [('offer completed', 'past_completed_count'), ('offer received', 'past_received_count')]:
        h = t[t.event.eq(ev)].groupby(['person', 'time']).size().rename('n').reset_index().sort_values(['time', 'person'])
        h[col] = h.groupby('person').n.cumsum()
        hist_sources.append((h[['person', 'time', col]], col))

    r = r.sort_values(['time', 'person'])
    r = pd.merge_asof(
        r,
        tx[['person', 'time', 'past_transaction_count', 'past_total_spend', 'past_average_spend']],
        on='time',
        by='person',
        direction='backward',
        allow_exact_matches=False
    )
    cols = ['past_transaction_count', 'past_total_spend', 'past_average_spend', 'past_completed_count', 'past_received_count']
    for h, col in hist_sources:
        r = pd.merge_asof(r.sort_values(['time', 'person']), h, on='time', by='person', direction='backward', allow_exact_matches=False)
    r[cols] = r[cols].fillna(0)
    progress(70, 'Customer history features created')

    r = r.merge(p, on='person', validate='many_to_one')

    # แบ่งข้อมูลแบบ Customer-disjoint 70/15/15
    people = pd.Series(sorted(r.person.unique())).sample(frac=1, random_state=42).tolist()
    n = len(people)
    a, b = int(n * 0.7), int(n * 0.85)
    mapping = {person: ('train' if i < a else 'validation' if i < b else 'test') for i, person in enumerate(people)}
    r['split'] = r.person.map(mapping)
    progress(78, 'Training, validation and test sets assigned')

    train_mask = r.split.eq('train')
    medians = {c: float(r.loc[train_mask, c].median()) for c in ['age', 'income']}
    for c, m in medians.items():
        r[c] = r[c].fillna(m)

    numeric = [
        'age', 'income', 'age_missing', 'income_missing', 'gender_missing',
        'member_year', 'member_month', 'reward', 'difficulty', 'duration_hours',
        'channel_email', 'channel_mobile', 'channel_social', 'channel_web'
    ] + cols

    categories = {c: sorted(r.loc[train_mask, c].unique().tolist()) for c in ['gender', 'offer_type']}
    X = r[numeric].astype(float).copy()
    for c, values in categories.items():
        for value in values:
            X[c + '_' + str(value)] = r[c].eq(value).astype(int)

    means = X.loc[train_mask].mean()
    scales = X.loc[train_mask].std(ddof=0).replace(0, 1)
    scaled = (X - means) / scales

    summary['splits'] = {}
    ids = {}
    for split in ['train', 'validation', 'test']:
        mask = r.split.eq(split)
        ids[split] = set(r.loc[mask, 'person'])

        features = X.loc[mask].reset_index(drop=True)
        features['completed'] = r.loc[mask, 'completed'].to_numpy()
        assert not features.isna().any().any()
        assert np.isfinite(features.to_numpy()).all()
        features.to_csv(out / (split + '.csv'), index=False)

        sf = scaled.loc[mask].reset_index(drop=True)
        sf['completed'] = r.loc[mask, 'completed'].to_numpy()
        sf.to_csv(out / (split + '_scaled.csv'), index=False)

        summary['splits'][split] = {
            'rows': int(mask.sum()),
            'customers': len(ids[split]),
            'positive': int(r.loc[mask, 'completed'].sum()),
            'positive_rate': float(r.loc[mask, 'completed'].mean())
        }
        progress({'train': 84, 'validation': 88, 'test': 92}[split], f'Saved {split}.csv')

    assert not (ids['train'] & ids['validation'] or ids['train'] & ids['test'] or ids['validation'] & ids['test'])

    meta = ['receipt_id', 'person', 'offer_id', 'time', 'expires_at', 'split', 'completed']
    r[meta + numeric + ['gender', 'offer_type']].to_csv(out / 'prepared_data_with_metadata.csv', index=False)

    params = {
        'imputation_medians': medians,
        'categories': categories,
        'feature_order': X.columns.tolist(),
        'scaler_mean': means.to_dict(),
        'scaler_scale': scales.to_dict(),
        'random_state': 42,
        'split_method': 'pandas sample on sorted unique customers; customer 70/15/15',
        'source': str(src)
    }
    (out / 'preprocessing_parameters.json').write_text(json.dumps(params, ensure_ascii=False, indent=2), encoding='utf-8')
    summary['feature_count'] = len(X.columns)
    summary['missing_features_after'] = int(X.isna().sum().sum())
    summary['validation_checks'] = [
        'unique receipt IDs',
        'no customers shared between splits',
        'no missing or infinite features',
        'historical events strictly before receipt',
        'full offer follow-up',
        'overlapping identical-offer receipts excluded',
        'preprocessing fitted on training only'
    ]
    (out / 'summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding='utf-8')
    progress(100, 'Data preparation complete')
    print("\nสรุปผลการจัดเตรียมข้อมูล:")
    print(json.dumps(summary['splits'], ensure_ascii=False, indent=2))

if __name__ == '__main__':
    main()

import pandas as pd
import numpy as np
import joblib
from pathlib import Path

from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from lightgbm import LGBMClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score

# 1. โหลดข้อมูลจากโฟลเดอร์ output ที่สร้างไว้
out_dir = Path('./output')

train_df = pd.read_csv(out_dir / 'train.csv')
val_df = pd.read_csv(out_dir / 'validation.csv')

train_sc = pd.read_csv(out_dir / 'train_scaled.csv')
val_sc = pd.read_csv(out_dir / 'validation_scaled.csv')

X_train, y_train = train_df.drop(columns=['completed']), train_df['completed']
X_val, y_val = val_df.drop(columns=['completed']), val_df['completed']

X_train_sc = train_sc.drop(columns=['completed'])
X_val_sc = val_sc.drop(columns=['completed'])

# 2. เปรียบเทียบโมเดล 3 รูปแบบ
models = {
    'Logistic Regression': (LogisticRegression(max_iter=1000, random_state=42), X_train_sc, X_val_sc),
    'Random Forest': (RandomForestClassifier(n_estimators=100, max_depth=8, random_state=42), X_train, X_val),
    'LightGBM': (LGBMClassifier(n_estimators=100, max_depth=5, learning_rate=0.05, random_state=42, verbose=-1), X_train, X_val)
}

print("=== กำลังฝึกสอนและเปรียบเทียบโมเดลบน Validation Set ===")
for name, (model, xtr, xval) in models.items():
    model.fit(xtr, y_train)
    preds = model.predict(xval)
    probs = model.predict_proba(xval)[:, 1]

    print(f"\n[{name}]")
    print(f"Accuracy : {accuracy_score(y_val, preds):.4f}")
    print(f"F1-Score : {f1_score(y_val, preds):.4f}")
    print(f"ROC-AUC  : {roc_auc_score(y_val, probs):.4f}")

# 3. จูน Optimal Threshold เพื่อความคุ้มค่าทางธุรกิจ (Creative Twist)
lgbm_model = models['LightGBM'][0]
val_probs = lgbm_model.predict_proba(X_val)[:, 1]

thresholds = np.linspace(0.2, 0.8, 61)
best_f1, best_th = 0, 0.5
for th in thresholds:
    score = f1_score(y_val, (val_probs >= th).astype(int))
    if score > best_f1:
        best_f1 = score
        best_th = th

print(f"\nOptimal Decision Threshold ที่ดีที่สุด: {best_th:.2f} (ให้ F1-Score = {best_f1:.4f})")

test_df = pd.read_csv(out_dir / 'test.csv')
X_test, y_test = test_df.drop(columns=['completed']), test_df['completed']

test_probs = lgbm_model.predict_proba(X_test)[:, 1]
test_preds = (test_probs >= best_th).astype(int)

train_auc = roc_auc_score(y_train, lgbm_model.predict_proba(X_train)[:, 1])
test_auc = roc_auc_score(y_test, test_probs)

print("\n=== ตรวจสอบ Overfitting ===")
print(f"Train AUC: {train_auc:.4f} | Test AUC: {test_auc:.4f}")
print(f"ผลต่าง (Gap): {abs(train_auc - test_auc):.4f} (ไม่ Overfitting หาก Gap ไม่เกิน 0.05)")

# บันทึกโมเดลไว้ทำ Web App ใน Step 5
artifact = {
    'model': lgbm_model,
    'features': X_train.columns.tolist(),
    'threshold': float(best_th)
}
joblib.dump(artifact, 'starbucks_offer_model.pkl')
print("\nบันทึกโมเดล 'starbucks_offer_model.pkl' พร้อมใช้งานสำหรับ Web App แล้ว")

